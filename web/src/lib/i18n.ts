// Two languages, one bundle. Swedish lives at /, English at /en (and /en/cv, /en/lab/{id}…).
// UI strings come from the dictionary below; the content document comes from /api/content?lang=.
export type Locale = "sv" | "en";

const rawPath = window.location.pathname;
export const locale: Locale = rawPath === "/en" || rawPath.startsWith("/en/") ? "en" : "sv";

// The path without the language prefix, used for routing.
export const sitePath = locale === "en" ? rawPath.replace(/^\/en/, "") || "/" : rawPath;

// Localised link: L("/cv") -> "/cv" or "/en/cv"; L("/") -> "/" or "/en"; anchors pass through.
export function L(path: string): string {
  if (path === "/boka") return locale === "en" ? "/en/book" : "/boka";
  if (path === "/nu") return locale === "en" ? "/en/now" : "/nu";
  if (locale === "sv" || !path.startsWith("/")) return path;
  if (path === "/") return "/en";
  if (path.startsWith("/#")) return "/en" + path.slice(1);
  return "/en" + path;
}

// The same page in the other language.
export function otherLocaleUrl(): string {
  const hash = window.location.hash;
  if (locale === "en") return (sitePath === "/" ? "/" : sitePath) + hash;
  return (sitePath === "/" ? "/en" : "/en" + sitePath) + hash;
}

